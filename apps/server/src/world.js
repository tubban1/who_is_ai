export function getConfiguredModels() {
  const envModels = (process.env.AI_MODELS || process.env.AI_MODEL || 'Claude-3.5-Sonnet,GPT-4o,Gemini-1.5-Pro')
    .split(',')
    .map(s => s.trim())
    .filter(Boolean);
  return envModels.length > 0 ? envModels : ['Claude-3.5-Sonnet', 'GPT-4o', 'Gemini-1.5-Pro'];
}

export function createSingleAgent(id, models) {
  const lang = AGENT_LANGUAGES[Math.floor(Math.random() * AGENT_LANGUAGES.length)];
  const name = getRandomName(lang);
  const model = models[Math.floor(Math.random() * models.length)];
  const spawnLeft = Math.random() < 0.5;
  const spawnX = spawnLeft ? (-54 - Math.random() * 4) : (54 + Math.random() * 4);
  const spawnZ = -8 + Math.random() * 12;
  const targetX = spawnLeft ? (-25 + Math.random() * 50) : (25 - Math.random() * 50);
  const targetZ = -7 + Math.random() * 11;
  const lifespan = 90000 + Math.random() * 150000; // 1.5 - 4 minutes active session

  return {
    id,
    displayName: name,
    type: 'ai',
    model,
    nativeLanguage: lang,
    x: spawnX,
    z: spawnZ,
    rotation: spawnLeft ? 0 : Math.PI,
    status: 'available',
    seed: Math.floor(Math.random() * 100000),
    targetX,
    targetZ,
    chatCooldownUntil: Date.now() + 3000 + Math.random() * 4000,
    sessionExpiresAt: Date.now() + lifespan,
    departing: false
  };
}

export function recycleAgent(agent, models = null) {
  const modelList = (models && models.length > 0) ? models : getConfiguredModels();
  const lang = AGENT_LANGUAGES[Math.floor(Math.random() * AGENT_LANGUAGES.length)];
  const name = getRandomName(lang);
  const model = modelList[Math.floor(Math.random() * modelList.length)];
  const newId = `a_${Date.now().toString(36).slice(-4)}_${Math.random().toString(36).slice(2, 6)}`;

  agent.id = newId;
  agent.displayName = name;
  agent.nativeLanguage = lang;
  agent.model = model;
  agent.seed = Math.floor(Math.random() * 100000);
  agent.status = 'available';
  agent.chatCooldownUntil = Date.now() + 2000 + Math.random() * 3000;
  agent.targetX = Math.max(-50, Math.min(50, agent.x + (Math.random() - 0.5) * 30));
  agent.targetZ = Math.max(-8, Math.min(4, agent.z + (Math.random() - 0.5) * 10));
  agent.idleUntil = 0;
  agent.sessionExpiresAt = Date.now() + 120000 + Math.random() * 120000;
  agent.departing = false;
  return agent;
}

export function createAiPopulation(count=18) {
  const models = getConfiguredModels();
  return Array.from({length:count}, (_,i)=>{
    const lang = AGENT_LANGUAGES[i % AGENT_LANGUAGES.length];
    const name = getRandomName(lang);
    return {
      id:`a_${String(i+1).padStart(2,'0')}`,
      displayName: name,
      type:'ai',
      model:models[i%models.length],
      nativeLanguage: lang,
      x: -45 + ((i * 13) % 90),
      z: -7 + ((i * 3) % 11),
      rotation: 0,
      status: 'available',
      seed: i * 97 + 13,
      targetX: -40 + ((i * 11) % 80),
      targetZ: -6 + ((i * 5) % 10),
      chatCooldownUntil: Date.now() + 2500 + (i % 3) * 1500,
      sessionExpiresAt: Date.now() + 45000 + (i * 12000) + Math.random() * 60000,
      departing: false
    };
  });
}

let lastSpawnTime = 0;

/**
 * 动态计算目标 AI Agent 规模 (Elastic Population Scaling)
 * 核心考量：
 * 1. 初期真人极少（0~1 人）时：保持基础底数（MIN=14），外滩依然人群络绎不绝、夜景繁华，绝不冷场；
 * 2. 真人逐渐增多（2~8 人）：AI 数量稳步微调（14~18 人），保证漫步偶遇概率高，真人比例适度提升；
 * 3. 真人较多（9~25 人）：AI 数量快速跟进（18~28 人），真人和 AI 比例逐渐收敛到 1:1 左右的黄金平衡区间；
 * 4. 高并发真人（30+ 人）：达到 MAX=36 人保护上限，防止服务器过载。
 */
export function getTargetAiPopulation(activeHumansCount) {
  const minAgents = Number(process.env.AI_POPULATION_MIN || 14);
  const maxAgents = Number(process.env.AI_POPULATION_MAX || 36);

  if (activeHumansCount <= 1) {
    return minAgents;
  }
  if (activeHumansCount <= 8) {
    return Math.min(maxAgents, Math.round(minAgents + (activeHumansCount - 1) * 0.5));
  }
  if (activeHumansCount <= 20) {
    return Math.min(maxAgents, Math.round(14 + (activeHumansCount - 1) * 0.75));
  }
  return Math.min(maxAgents, Math.max(minAgents, activeHumansCount));
}

export function tickAgents(agents, dt=0.7, humans=null) {
  const now = Date.now();
  const models = getConfiguredModels();
  const activeHumans = humans ? Array.from(humans.values()).filter(h => (h.status === 'available' || !h.status) && now - (h.lastSeen || 0) < 30000) : [];
  const targetAi = getTargetAiPopulation(activeHumans.length);

  // 1. 平滑扩容 (Scale Up)：当前总数低于目标，每隔至少 2.5 秒从步道外围走入 1 位新路人
  if (agents.length < targetAi && now - lastSpawnTime > 2500) {
    lastSpawnTime = now;
    const newId = `a_${now.toString(36).slice(-4)}_${Math.random().toString(36).slice(2, 6)}`;
    const newAgent = createSingleAgent(newId, models);
    agents.push(newAgent);
  }

  // 2. 平滑缩容标记 (Scale Down Initiator)：如果当前总数超出目标，寻找处于 available 且未在会话中的路人走向出口
  if (agents.length > targetAi) {
    const departingCount = agents.filter(a => a.departing).length;
    const excess = agents.length - targetAi;
    if (departingCount < excess) {
      const candidate = agents.find(a => a.status === 'available' && !a.departing);
      if (candidate) {
        candidate.departing = true;
        candidate.targetX = candidate.x > 0 ? 58 : -58;
        candidate.targetZ = candidate.z;
        candidate.idleUntil = 0;
      }
    }
  }

  // 3. 倒序遍历更新位置与状态（支持安全动态剔除与转生）
  for (let i = agents.length - 1; i >= 0; i--) {
    const a = agents[i];

    // If agent is currently chatting, keep them active & refresh session so they don't leave mid-chat
    if (a.status !== 'available') {
      a.sessionExpiresAt = Math.max(a.sessionExpiresAt || 0, now + 120000);
      a.departing = false;
      continue;
    }

    // Natural Player Turnover / Dynamic lifecycle:
    // When session time expires, the agent naturally starts walking towards the exit promenade
    if (a.sessionExpiresAt && now > a.sessionExpiresAt && !a.departing) {
      a.departing = true;
      // Head to the nearest edge/exit
      a.targetX = a.x > 0 ? 58 : -58;
      a.targetZ = a.z;
      a.idleUntil = 0;
    }

    // If departing agent reaches the edge or timeout expires
    if (a.departing && (Math.abs(a.x) >= 54 || now > a.sessionExpiresAt + 35000)) {
      if (agents.length > targetAi) {
        // 超出目标人口：平滑离场真正缩容
        agents.splice(i, 1);
        continue;
      } else {
        // 未超出目标人口：退役并以新路人身份重新入场
        const newPerson = createSingleAgent(`a_${Date.now().toString(36).slice(-4)}_${Math.random().toString(36).slice(2,5)}`, models);
        Object.assign(a, newPerson);
        continue;
      }
    }

    // 1. Natural idle/pause state (looking at river scenery, smartphone, or daydreaming)
    if (a.idleUntil && now < a.idleUntil) {
      // Occasionally turn head / adjust viewing angle slightly while idle
      if (Math.random() < 0.15) {
        a.rotation += (Math.random() - 0.5) * 0.4;
      }
      continue;
    }

    let dx = a.targetX - a.x;
    let dz = a.targetZ - a.z;
    let d = Math.hypot(dx, dz);

    // 2. Reached destination
    if (d < 1.0) {
      // If departing, keep walking out
      if (a.departing) {
        a.x += (a.x > 0 ? 1 : -1) * 1.5 * dt;
        continue;
      }

      // 45% chance to stop and idle for 2 to 5.5 seconds like a real person browsing the Bund promenade
      if (Math.random() < 0.45 && !a.idleUntil) {
        a.idleUntil = now + 2000 + Math.random() * 3500;
        continue;
      }
      a.idleUntil = 0;

      if (activeHumans.length > 0 && Math.random() < 0.45) {
        const targetHuman = activeHumans[Math.floor(Math.random() * activeHumans.length)];
        const angle = Math.random() * Math.PI * 2;
        const offset = 1.8 + Math.random() * 1.6;
        a.targetX = Math.max(-52, Math.min(52, targetHuman.x + Math.cos(angle) * offset));
        a.targetZ = Math.max(-8, Math.min(4, targetHuman.z + Math.sin(angle) * offset));
      } else {
        a.targetX = -48 + Math.random() * 96;
        a.targetZ = -8 + Math.random() * 12;
      }
      dx = a.targetX - a.x;
      dz = a.targetZ - a.z;
      d = Math.hypot(dx, dz);
    }

    const speed = (a.departing ? 1.6 : 1.2) + (a.seed % 5) * 0.15;
    if (d > 0.05) {
      a.x += (dx / d) * speed * dt;
      a.z += (dz / d) * speed * dt;
      a.rotation = Math.atan2(dx, dz);
    }
  }
}

export function distance(a,b) { return Math.hypot((a.x||0)-(b.x||0),(a.z||0)-(b.z||0)); }

export function sceneObservation(entity) {
  const landmarks = [
    {name:'Oriental Pearl Tower & Lujiazui Skyline across the river',x:0,z:-65},
    {name:'Peace Hotel green pyramid copper roof',x:-18,z:25},
    {name:'Customs House Big Ching bell clock tower',x:22,z:25},
    {name:'The Bund elevated waterfront promenade',x:0,z:-6},
    {name:'Huangpu River cruise ferry',x:18,z:-40}
  ];
  return landmarks.map(l=>({...l,distance:Math.round(Math.hypot(entity.x-l.x,entity.z-l.z))})).sort((a,b)=>a.distance-b.distance).slice(0,3);
}
